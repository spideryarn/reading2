export function Library({
  readerId,
}: {
  /**
   * Whose shelf this is, from `SignedIn` in App.tsx.
   *
   * A prop rather than `user?.id` off the `useSession()` below, even though the
   * two are the same string: `useShelf` reads this reader's saved copy out of
   * IndexedDB before the live answer lands, and *which reader* is then a fact
   * the shelf depends on rather than a detail of the chrome. `SignedIn` has a
   * non-optional `User`, so passing it down makes the id non-optional here —
   * the `?.` that `useSession` forces on every other caller cannot creep into
   * the one place it would mean "look in nobody's cache".
   * docs/plans/260903g-faster-shelf-load-and-tidier-homepage-controls.md § Stage 5.
   */
  readerId: string;
}) {
  useRenderCount("Library");
  /* Who the Admin link is drawn for, and whose address the Profile tooltip
     names. `useSession` is already subscribed once at the top of the app
     (App.tsx), and a second subscription is one listener rather than a second
     source of truth — the SDK is the source, and both read it. */
  const { user } = useSession();
  const shelf = useShelf(readerId);
  const { articles, error, reload } = shelf;
  const slow = useSlow(articles === null);

  /* Every one of these is in the URL rather than in `useState`, which is the
     rule the whole app runs on (docs/project/url-state.md): reload the
     homepage, or send somebody the link, and you get the same shelf back.
     Until 2026-08-26 the search box was `useState` and the order was whatever
     the server happened to send, so neither survived a reload. */
  const [rawQuery, setQuery] = useQueryState("q", libraryQueryParam);
  const [by, setBy] = useQueryState("by", libraryByParam);
  const [rawDir, setDir] = useQueryState("dir", sortDirParam);
  const [view, setView] = useQueryState("view", libraryViewParam);
  const [show, setShow] = useQueryState("show", libraryShowParam);

  /**
   * Whether the shelf is showing every row or only the first `SHELF_ROW_CAP`.
   *
   * **One flag for both views, not one each.** The two views are the same list
   * painted twice (url-state.md), so if the list is "all of them" in one
   * painting it is all of them in the other; a per-view flag would quietly make
   * the view switch a filter as well. There is no "show fewer", so the only
   * thing two flags would buy is pressing the button a second time.
   *
   * **Deliberately not in the URL**, unlike every other bit of state on this
   * page. The rule in docs/project/url-state.md is that the query string says
   * *how you are looking at* the shelf, and this is nearer to a scroll position
   * than to a view: nobody wants to send somebody a link to the first fifty.
   *
   * **And deliberately here rather than inside `DataTable`.** As component-local
   * state it would reset every time that component unmounted — which is on every
   * switch to cards and every search that matches nothing — so "show all" would
   * have quietly undone itself in exactly the places a reader would notice.
   * GPT Sol, 2026-09-06.
   *
   * It does *not* reset when the search changes, which is the other half of the
   * same choice: "show me all of them" reads as a standing preference, not as an
   * answer to one query.
   */
  const [expanded, setExpanded] = useState(false);

  const query = rawQuery ?? "";

  /* The tab. Bare, this is the homepage and so the one page that leads with the
     app's own name; narrow the shelf and what you narrowed it to takes the
     front instead. See src/web/page-title.ts. */
  useDocumentTitle(pageTitle({ kind: "library", query, unread: show === "unread" }));

  /**
   * Make a `push` change to the view, taking any half-typed search with it.
   *
   * `?q=` is written on a 200ms debounce, so a click landing inside that window
   * pushes a history entry that does not have the query in it yet — and the
   * query then *replaces* itself into the new entry a moment later. Back then
   * undoes the sort **and** the search together, having appeared to record only
   * the sort. Writing `q` here with the limit lifted puts it in the same batch
   * as the push, so one entry carries both. nuqs queues every synchronous write
   * until the next tick and flushes them as one URL update, which is also why
   * `setBy` and `setDir` are one history entry rather than two.
   *
   * Caught by a cross-family review, 2026-08-26.
   */
  const pushView = useCallback(
    (write: () => void) => {
      write();
      void setQuery(query || null, { limitUrlUpdates: throttle(0) });
    },
    [query, setQuery],
  );

  /* One clock reading, re-read once a minute and handed to everything that
     prints a relative date — see useNow.ts for both halves of why. */
  const now = useNow();

  const columns = useMemo(() => libraryColumns(shelf, now), [shelf, now]);
  const natural = useMemo(() => naturalDirections(columns), [columns]);
  /* `DEFAULT_BY` as the fallback: a URL naming nothing we recognise lands on
     the ordinary shelf rather than on an unsorted list with no chip pressed.

     **`rawDir` straight in, `null` and all.** No `dir` in the URL means "each
     key goes whichever way it naturally goes", which is a different answer per
     column, so `sortingFromUrl` fills the gaps rather than nuqs supplying a
     default (params.ts § sortDirParam has the hour that rule cost). This line
     used to read `rawDir ?? []` above the memo — a fresh array every render,
     which made this memo re-run every render, which made TanStack recompute and
     queue a page-index reset, which set state and rendered again, for ever:
     docs/postmortems/260827e-shelf-render-loop.md. */
  const sorting = useMemo(
    () => sortingFromUrl(by, rawDir, natural, DEFAULT_BY),
    [by, rawDir, natural],
  );

  /* Matcher one: the shelf itself, filtered in the browser, then narrowed by
     the Unread chip. The *order* is no longer ours — TanStack owns it below —
     but which rows exist still is.

     `useMemo` because this runs on every keystroke over every article, and
     because the identity of the array it returns is what decides whether the
     whole table is rebuilt. */
  const rows = useMemo(() => {
    if (!articles) return null;
    const found = filterEntries(articles, query);
    return show === "unread" ? found.filter((a) => a.opens === 0) : found;
  }, [articles, query, show]);

  /**
   * The sorting state, written straight back to the address bar.
   *
   * TanStack hands us an updater rather than a value — it computes what a click
   * means, including which end a new column starts at and whether shift was
   * held — so this applies it to the current state and serialises the result.
   * That is the whole of what replaced a hand-written `nextSort`.
   */
  const onSortingChange = useCallback<OnChangeFn<SortingState>>(
    (updater) => {
      /* Applied to `sorting` — the very array TanStack was handed as its state,
         so what it computed the update against and what we apply it to cannot
         be two different things. */
      const next = functionalUpdate(updater, sorting);
      /* Never empty. `enableSortingRemoval: false` should make that impossible,
         but an empty sort would fall back to whatever order the data arrived
         in — a state the reader cannot name or ask for — so it is refused here
         as well as configured against. */
      if (next.length === 0) return;
      const url = sortingToUrl(next);
      pushView(() => {
        void setBy(url.by);
        /* Left out when it says nothing the columns would not have said
           themselves, which keeps `?by=title` short — and correct, since an
           absent `dir` is what makes the per-column fallback run at all. */
        void setDir(isAllNatural(next, natural) ? null : url.dir);
      });
    },
    [sorting, natural, pushView, setBy, setDir],
  );

  const table = useSortedTable({
    data: rows ?? EMPTY,
    columns,
    sorting,
    onSortingChange,
    rowId: slugOf,
  });

  /* The fixture last, in every order and both directions. It is a committed
     placeholder rather than something the reader added, and the server has
     always kept it at the foot of the shelf — sorting in the browser without
     carrying that over puts a demo excerpt above the reader's own library the
     first time anybody sorts by length. */
  const modelRows = table.getRowModel().rows;
  const primary = sorting[0]?.id;
  const sorted = useMemo(() => {
    /* Two sinks, in this order.

       **Missing values last, whichever way the arrow points.** `sortUndefined`
       is the option for this and it is switched off, because TanStack gets it
       wrong when two values are both missing — see lib/table-sort.ts §
       numberOrMissing. So the columns sort missing *low*, consistently, and the
       rows whose primary key is missing are moved down here. Ascending by "last
       opened" must not fill the top of the shelf with everything you have never
       opened: that is a useful thing to want, and it is what the Unread chip is
       for.

       **Then the fixture**, below even those. It is a committed placeholder
       rather than something the reader added, and the server has always kept it
       at the foot of the shelf. */
    const missingLast = primary
      ? sinkLast(modelRows, (r) => r.getValue(primary) === undefined)
      : modelRows;
    return sinkLast(missingLast, (r) => !!r.original.fixture);
  }, [modelRows, primary]);

  // Reload the shelf the moment a job finishes, rather than telling the reader
  // to reload the page — they just watched the five steps go green, and an
  // empty shelf underneath would read as a failure.
  const queue = useJobs(reload);

  // Matcher two: the passages inside the articles, from the server.
  const passages = useLibrarySearch(query);

  const searching = query.trim().length > 0;
  const total = articles?.length ?? 0;
  const showing = rows?.length ?? 0;
  // Said only when something is actually being hidden. "12 of 12" is noise.
  const narrowed = (searching || show === "unread") && showing !== total;

  /* The slugs the Unread chip lets through, whatever the search box says — the
     passages are the answer to the search, so narrowing them by the search
     twice would be wrong. `null` when the chip is off, which is "do not narrow"
     rather than "narrow to nothing". */
  const unread = useMemo(
    () =>
      show === "unread" && articles
        ? new Set(articles.filter((a) => a.opens === 0).map((a) => a.slug))
        : null,
    [articles, show],
  );

  /* Whichever column is sorted first decides what a card says about itself. */
  const note = CARD_NOTES[sorting[0]?.id ?? ""] ?? ADDED_NOTE;

  /* What this view draws, and whether there is a "show all" to offer. Taken
     from `sorted`, which is after both `sinkLast` passes — capping before the
     sort would pick its fifty out of the wrong order. lib/row-cap.ts. */
  const capped = capRows(sorted, SHELF_ROW_CAP[view], expanded);

  return (
    <main className="tw:mx-auto tw:max-w-4xl tw:px-6 tw:py-10 tw:font-sans">
      <header className="tw:mb-8">
        {/* The masthead links are deliberately the quietest thing on the page —
            same faint-until-hovered treatment as the back-link in Masthead.tsx,
            so the two read as one convention. This paragraph used to argue that
            the design reference in particular should not be stepped over by a
            reader arriving at their shelf; it is on /admin since 2026-09-05,
            which is that argument taken to its conclusion. */}
        {/* Wraps rather than letting the links crush the wordmark in a narrow
            window. They keep `justify-between` when they fit and drop to their
            own line when they do not — and `gap-y-1` keeps that second line off
            the strapline below. */}
        <div className="tw:flex tw:flex-wrap tw:items-baseline tw:justify-between tw:gap-x-4 tw:gap-y-1">
          {/* The spider beside the name, which every other page has had since
              2026-08-26 and this one — the page the app opens on — did not.
              Greg, 2026-09-08: *"can you include the logo itself in the
              top-left of the logged-in Homepage next to the wordmark"*.

              **Deliberately not `HomeLogo`, and deliberately not animated.**
              This is home, so there is nothing to link to (App.tsx says why),
              and the hover animations are calibrated in whole pixels against a
              0.82rem wordmark and a 20px spider — a 2px pluck is invisible on a
              30px heading, and `spya-radius` masks at a hard-coded `20px 20px`.
              Making them travel here means expressing the whole set in `em`,
              which is a rework rather than a class. styles/logo-animations.css.

              `items-center` in its own row so the glyph centres on the word
              while the header's outer flex keeps its baseline alignment for the
              links opposite. */}
          <div className="tw:flex tw:items-center tw:gap-2.5">
            {/* `alt=""`: the wordmark is right there, and a screen reader
                reading the name twice is how a decorative image becomes noise.
                Same reasoning as HomeLogo.tsx. */}
            <img
              className="logo-image"
              src="/spideryarn-logo.png"
              alt=""
              width={28}
              height={28}
            />
            <h1 className="tw:font-prose tw:text-3xl tw:text-foreground">Spideryarn</h1>
          </div>
          {/* One group, so that once the first card is up its neighbour opens
              instantly as the pointer runs along the row — Tooltip.tsx. The
              delays are the ones the dock and the metadata cards use, because
              this is the same kind of thing: a short row of quiet chrome whose
              labels are already visible, where the tooltip adds a sentence
              rather than naming the button. */}
          <TooltipGroup delay={{ open: 300, close: 120 }} timeoutMs={400}>
            <div className="tw:flex tw:items-baseline tw:gap-4">
              {/* Home is where a global thing gets a way in. The profile page
                  holds what is true of the reader on every article, so a link to
                  it from inside one article would be a link nobody finds —
                  docs/project/reader-profile.md. It used to be ordered before
                  Design on the grounds that this one is for the reader and that
                  one was developer furniture; Design left for /admin on
                  2026-09-05, which settled the argument. */}
              <Tooltip
                placement="bottom"
                keepSide
                content={
                  <Tip>
                    What the model knows about who it is writing for.
                    {/* The address is the answer to "am I signed in as the
                        right person", which is the question this link gets
                        asked most. Second, under what the page is for, and
                        simply absent until the session arrives — a card saying
                        "Signed in as undefined" is worse than one that does not
                        mention it. */}
                    {user?.email && (
                      <span className="tw:mt-1 tw:block tw:text-ink-faint">
                        {/* `break-all` on the address alone: `.tooltip` caps at
                            22rem and sets no `overflow-wrap`, so a long address
                            with nothing to break on would run out of the panel
                            rather than wrap. GPT Sol, 2026-08-28. */}
                        Signed in as <span className="tw:break-all">{user.email}</span>
                      </span>
                    )}
                  </Tip>
                }
              >
                <Link
                  href={PROFILE_HREF}
                  className="tw:inline-flex tw:items-center tw:gap-1.5 tw:text-xs tw:text-ink-faint tw:no-underline tw:hover:text-highlight"
                >
                  <User size={13} />
                  Profile
                </Link>
              </Tooltip>
              {/* **Only the administrator sees this, and only the server enforces
                  it.** Drawing or not drawing a link is a courtesy — the page is
                  in the bundle either way, and typing the address gets a
                  non-administrator the shelf back (App.tsx). src/admin.ts. */}
              {isAdmin(user?.id) && (
                <Tooltip
                  placement="bottom"
                  keepSide
                  content={<Tip>Who has signed up, and how much they have read.</Tip>}
                >
                  <Link
                    href={ADMIN_HREF}
                    className="tw:inline-flex tw:items-center tw:gap-1.5 tw:text-xs tw:text-ink-faint tw:no-underline tw:hover:text-highlight"
                  >
                    <Shield size={13} />
                    Admin
                  </Link>
                </Tooltip>
              )}
              {/* **Design is not here any more**, since 2026-09-05:
                  > Move the Design link on the logged-in Homepage into /admin
                  > — Greg, 2026-09-05 (SPIDERYARN-READING2-1T)

                  It is an `Entry` on the /admin index now (AdminPage.tsx). The
                  masthead is for things a reader does — their profile, their
                  shelf — and a page of colour tokens is developer furniture that
                  every signed-in reader was being shown. Note that moving the
                  *link* gates nothing: `/design` is still open to anybody signed
                  in, deliberately, for the reason admin.md gives about the Admin
                  link beside this one. */}
            </div>
          </TooltipGroup>
        </div>
        <p className="tw:mt-1 tw:text-sm tw:text-muted-foreground">
          Read deeply, at whatever level of detail you need. Pick a piece.
        </p>
      </header>

      <AddArticle queue={queue} />

      {error && (
        <p className="tw:rounded-md tw:border tw:border-destructive/40 tw:bg-destructive/10 tw:p-4 tw:text-sm tw:text-foreground">
          {error}
        </p>
      )}
      {shelf.actionError && (
        <p className="tw:mb-3 tw:rounded-md tw:border tw:border-destructive/40 tw:bg-destructive/10 tw:px-4 tw:py-2 tw:text-sm tw:text-foreground">
          {shelf.actionError}
        </p>
      )}

      {shelf.undoable && (
        <UndoStrip title={shelf.undoable.title} onUndo={() => void shelf.undo()} />
      )}

      {/* **Directly above the list it filters**, and below the box for adding
          one, since 2026-09-03:

          > Move the search bar so it's just above the list of articles.
          >
          > — Greg, 2026-09-03

          It used to be the first thing under the header — so the box you use to
          *find* an article sat above the box you use to *add* one, with
          everything else between it and the list it narrows.

          `trim()` rather than `v || null`: spaces alone serialise to `?q=%20`,
          which the parser reads back as `null`. So the box emptied itself on
          reload while the URL still carried something — the one thing this
          page's URL state is supposed to make impossible. A value that merely
          *ends* in a space is kept as typed. */}
      <SearchBox value={query} onChange={(v) => void setQuery(v.trim() ? v : null)} />

      {/* The controls sit directly above the list they govern, and only once
          there is a list. A sort control over an empty shelf is furniture. */}
      {total > 0 && (
        <ShelfControls
          table={table}
          chipOrder={CHIP_ORDER}
          view={view}
          onView={(v) => pushView(() => void setView(v))}
          filter={show}
          onFilter={(f) => pushView(() => void setShow(f))}
        />
      )}

      {narrowed && (
        <p className="tw:mb-3 tw:mt-0 tw:text-xs tw:text-muted-foreground">
          {showing} of {total} {total === 1 ? "article" : "articles"}
        </p>
      )}

      {/* Silent until the wait is worth mentioning — on a warm shelf this fetch
          is over well before that, and a line that flashes up and away reads as
          a fault. After that, say what is being fetched. See useSlow.ts, which
          owns the threshold. */}
      {!error && articles === null && slow && (
        <p className="tw:text-sm tw:text-muted-foreground">Reading the shelf…</p>
      )}
      {articles?.length === 0 && (
        <p className="tw:text-sm tw:text-muted-foreground">
          Nothing on the shelf yet. Paste a URL above and it'll be here in a minute or two.
        </p>
      )}
      {showing === 0 && total > 0 && (
        <p className="tw:text-sm tw:text-muted-foreground">{nothingLeft(query, show)}</p>
      )}

      {/* One list, two renderers. The sort, the filter and the search are all
          resolved above this line, so neither view can disagree with the other
          about what is on the shelf or what order it is in — see
          ShelfControls.tsx. */}
      {/* **The first few, and a button for the rest.** Greg, 2026-09-06:

          > the table should by default only show the top 50? or so Articles,
          > with a button at the bottom to show all. Eventually we might consider
          > paging, but probably that's overkill for now

          He asked for the table and then asked for the cards too, so both are
          capped — at different numbers, for the reason under `SHELF_ROW_CAP`.

          Sliced **here**, after both `sinkLast` passes, rather than inside
          `DataTable`: the cap is caller policy, which is the same reason
          `DataTable` takes its rows as a prop rather than reading them off the
          table. It also could not carry the label — `DataTable`'s other consumer
          is /admin's list of accounts (AdminPage.tsx), and "Show all 213
          articles" is not a sentence a shared component can write.

          Slicing before the sort would cap the wrong fifty.

          **The button is outside the view switch, drawn once.** It was inside
          the table branch while the table was the only capped view, and the
          obvious way to cap the cards was to write it a second time next to the
          `<ul>` — two copies of one rule, which is the thing lib/row-cap.ts
          exists to stop happening. Here the branch chooses a renderer and
          nothing else, so a capped view without its button is not a shape this
          JSX can take. */}
      {sorted.length > 0 && (
        <>
          {view === "table" ? (
            <DataTable table={table} rows={capped.shown} caption="Your articles" />
          ) : (
            <ul className="tw:m-0 tw:flex tw:list-none tw:flex-col tw:gap-3 tw:p-0">
              {capped.shown.map((row) => (
                <li key={row.id}>
                  <ShelfCard entry={row.original} shelf={shelf} note={note(row.original, now)} />
                </li>
              ))}
            </ul>
          )}
          {/* Drawn exactly when `revealTotal` is a number, and that number is
              the only count it can print — see lib/row-cap.ts on why the slice
              and the button come from one call rather than two conditions that
              agree until somebody edits one of them. Note it is a sibling of
              the `<ul>` rather than a child: a bare `<button>` inside a list is
              invalid HTML, and the list has semantics a screen reader reads. */}
          {capped.revealTotal !== null && (
            <ShowAllRows total={capped.revealTotal} onShowAll={() => setExpanded(true)} />
          )}
        </>
      )}

      {/* The passages obey the Unread chip too. Without that, turning Unread on
          and searching for something only an opened article contains printed
          "No unopened article matches …" and then listed passages from that
          very article — two answers to one question, on one screen. The hidden
          ones are counted rather than silently dropped, because "it is in
          something you have already read" is the useful half of that answer. */}
      {searching && <Passages state={passages} query={query} only={unread} />}

      {!searching && <Archived shelf={shelf} />}

      {/* Greg's own example of a signed-in page that should carry one
          (2026-09-03). The shelf has a bottom, and it is where a reader who has
          been away comes back to — so it is where the policy and the feature
          list stay reachable long after the landing page stopped being shown to
          them.

          **`here` because this page is App.tsx's fallback**, exactly as the
          landing page is signed out: a non-administrator at `/admin` gets the
          shelf. Without this the row offered that reader a Home link to the
          shelf they were already looking at. GPT Sol, 2026-09-03.

          Every unrecognised address landed here too until later the same day,
          when they got a page of their own — NotFoundPage.tsx. One address
          still needs this, which is one more than none. SiteFooter.tsx §
          `here`. */}
      <SiteFooter here="library" />
    </main>
  );
}

/**
 * Why nothing is on screen.
 *
 * A shelf with articles on it and nothing matching is a different thing from an
 * empty shelf, and it has to say **which** of the two narrowings emptied it —
 * otherwise pressing Unread on a shelf you have read all of looks like the
 * search box has broken.
 */
function nothingLeft(query: string, show: ShelfFilter): string {
  const q = query.trim();
  if (q && show === "unread") return `No unopened article matches “${q}”.`;
  if (q) return `No article's title, author or blurb matches “${q}”.`;
  return "You have opened all of them.";
}

