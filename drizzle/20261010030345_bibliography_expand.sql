-- Each renamed step name's other spelling, or null. The one list of pairs the
-- step-run trigger reads; Stage 3 recreates it with its own pairs.
CREATE OR REPLACE FUNCTION "spideryarn"."step_name_partner"("name" text)
RETURNS text
LANGUAGE sql
IMMUTABLE
SET search_path = ''
AS $$
  SELECT CASE "name"
    WHEN 'citations' THEN 'bibliography'
    WHEN 'bibliography' THEN 'citations'
    ELSE NULL
  END
$$;--> statement-breakpoint

-- AFTER, per row. The partner row is replaced wholesale (delete, then insert
-- NEW with the partner's name), not upserted column by column, so a column
-- added to this table later is mirrored without anybody editing this
-- function. `pg_trigger_depth() > 1` is this trigger's own writes coming back
-- round, and a cascade from `article_revisions` (which deletes both spellings
-- anyway): neither is mirrored.
--
-- What the old code relies on is kept: an `UPDATE` it issues still reports its
-- own row count (a trigger's writes are not counted), so `finishStepRun`'s
-- `rowCount !== 1` fence still holds.
CREATE OR REPLACE FUNCTION "spideryarn"."revision_step_runs_mirror_renamed"()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  partner text;
BEGIN
  IF pg_trigger_depth() > 1 THEN
    RETURN NULL;
  END IF;
  IF TG_OP IN ('UPDATE', 'DELETE') THEN
    partner := "spideryarn"."step_name_partner"(OLD."step_name");
    IF partner IS NOT NULL THEN
      DELETE FROM "spideryarn"."revision_step_runs"
       WHERE "revision_id" = OLD."revision_id" AND "step_name" = partner;
    END IF;
  END IF;
  IF TG_OP IN ('INSERT', 'UPDATE') THEN
    partner := "spideryarn"."step_name_partner"(NEW."step_name");
    IF partner IS NOT NULL THEN
      DELETE FROM "spideryarn"."revision_step_runs"
       WHERE "revision_id" = NEW."revision_id" AND "step_name" = partner;
      INSERT INTO "spideryarn"."revision_step_runs"
      SELECT (jsonb_populate_record(NEW, jsonb_build_object('step_name', partner))).*;
    END IF;
  END IF;
  RETURN NULL;
END;
$$;--> statement-breakpoint

DROP TRIGGER IF EXISTS "revision_step_runs_mirror_renamed" ON "spideryarn"."revision_step_runs";--> statement-breakpoint
CREATE TRIGGER "revision_step_runs_mirror_renamed"
  AFTER INSERT OR UPDATE OR DELETE ON "spideryarn"."revision_step_runs"
  FOR EACH ROW EXECUTE FUNCTION "spideryarn"."revision_step_runs_mirror_renamed"();--> statement-breakpoint

-- **The postcondition**, because a copy that matched nothing and one that
-- worked print the same tick: every `citations` run has its twin, and every
-- revision's pair agrees.
DO $$
DECLARE missing bigint;
DECLARE unequal bigint;
BEGIN
  SELECT count(*) INTO missing
    FROM "spideryarn"."revision_step_runs" o
   WHERE o."step_name" = 'citations'
     AND NOT EXISTS (SELECT 1 FROM "spideryarn"."revision_step_runs" n
                      WHERE n."revision_id" = o."revision_id" AND n."step_name" = 'bibliography');
  SELECT count(*) INTO unequal
    FROM "spideryarn"."article_revisions"
   WHERE "citations" IS DISTINCT FROM "bibliography";
  IF missing > 0 OR unequal > 0 THEN
    RAISE EXCEPTION
      'migration bibliography_expand: % citations step run(s) without a bibliography twin and % revision(s) whose two columns differ', missing, unequal;
  END IF;
END $$;
