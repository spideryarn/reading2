-- **Why not a rename in place, as drizzle/20261001224759_skim.sql did.**
-- `npm run deploy` applies migrations and then waits for Vercel, so for those
-- minutes (and for as long as it takes if the build then fails) production
-- runs the pre-rename code against this schema. That code names
-- `article_revisions.citations` and the step `citations`; a column renamed in
-- place would fail every read of every revision. So this migration only ADDS,
-- and keeps both spellings true whichever version writes:
--
-- 1. `article_revisions.bibliography`, a copy of `citations`, and a BEFORE
--    trigger (`article_revisions_mirror_renamed`) that keeps the pair equal:
--    on insert whichever is null takes the other; on update whichever changed
--    is copied to the other (`IS DISTINCT FROM`, so clearing to null mirrors
--    too), and if one statement changes both, the new column wins.
-- 2. `revision_step_runs`: the CHECK (generated above) admits both names; the
--    `citations` rows are COPIED as `bibliography` rows (the old rows stay);
--    and an AFTER trigger (`revision_step_runs_mirror_renamed`) mirrors every
--    insert, update and delete on one spelling onto the other, guarded by
--    `pg_trigger_depth()` so its own writes do not mirror back. A lease the
--    old code takes on `citations` is the new code's lease on `bibliography`.
-- 3. `chat_threads`: the two origin CHECKs (generated above) admit
--    `bibliography` beside `citations`. Rows are NOT rewritten: the new code
--    reads `citations` as `bibliography` (src/thread-origin.ts) and writes the
--    new word.
-- 4. `jobs.steps` / `jobs.reset` are NOT rewritten: the new code reads the old
--    step name through `RETIRED_STEPS` (src/step-order.ts), as it does Skim's.
--    `ai_calls` is append-only, read through `currentLedgerName`.
--
