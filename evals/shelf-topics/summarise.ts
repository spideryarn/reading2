/**
 * **The numbers that need no judge** — plan 260929c § Reviews, R6. Free;
 * reads the run files and writes `results/summary.md`.
 *
 *     npx tsx evals/shelf-topics/summarise.ts
 *
 * Per case × arm, the mean over its runs of: coverage@5/8/12 and the largest
 * overlap among the first 12 (`shelfTermHeadMetrics`, the report script's one
 * definition); for labelled (synthetic) cases, how many planted distractors
 * and how many expected-good topics appear in the first 12, and how many of
 * each were candidates at all; cost per call and latency. Then the first 12 of
 * run 1 of every arm, to be read.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

import { candidatePool, shelfTermHeadMetrics, type ShelfTerm } from "../../src/shelf-terms/choose.js";
import { ARMS, chooseInput, DERIVED_ARMS, loadCases, RESULTS_DIR, type RunFile, RUNS } from "./case.js";

const HEAD = 12;
const mean = (xs: number[]) => (xs.length ? xs.reduce((s, x) => s + x, 0) / xs.length : Number.NaN);
const f2 = (x: number) => (Number.isNaN(x) ? "–" : x.toFixed(2));
const f1 = (x: number) => (Number.isNaN(x) ? "–" : x.toFixed(1));

/** `global workspace theory` counts for the label `global workspace`: whole words, in order. */
const containsPhrase = (key: string, phrase: string) => ` ${key} `.includes(` ${phrase} `);

const derived = new Set<string>(DERIVED_ARMS);
/** A derived arm is marked on every row, so it can never be read as predeclared. */
const armLabel = (arm: string) => (derived.has(arm) ? `${arm} †` : arm);
const topicCounts = new Map<string, number[]>();

const lines: string[] = [];
const spend = new Map<string, { usd: number; calls: number; errors: number }>();

lines.push("# Shelf topics eval — the numbers");
lines.push("");
lines.push(
  "Generated by `evals/shelf-topics/summarise.ts`. Means over the successful runs shown in `runs` (up to 3 per arm); failed runs are excluded from means and counted in `errors`. **cov@k**: share of eligible articles in the first k topics. " +
    "**maxJ / maxO**: the largest Jaccard / overlap coefficient between two of the first 12. **dis / good**: planted distractors / expected-good topics " +
    "among the first 12 (synthetic cases; a topic counts for an expected-good label when it contains the label's words in order, so *global workspace theory* counts for *global workspace*; distractors match exactly; the figure after the slash is how many of them were candidates at all). **$/call**: OpenRouter's settled cost, " +
    "or the upstream figure on a BYOK call. **topics**: how many topics the list has (at most 30) — a short row is a real cost. `greg-like` is first: it stands in for Greg's own shelf.",
  );
  lines.push(
    "",
    "**† jev-floor and jev-floor-0.75 were added after seeing the results; they were not predeclared.** Jev's expected scores never reach 0 " +
      "(on greg-like, food 0.86, female 0.90), so the greedy still took distractors to fill slots. These arms re-read the saved Jev scores, " +
      "set any below 1.0 (or 0.75) to 0 — not a topic — and run the same greedy. They make no model call; their cost is jev-score's.",
);

for (const c of loadCases()) {
  const input = chooseInput(c);
  const slugs = input.map((a) => a.slug);
  const poolKeys = new Set(candidatePool(input).map((p) => p.key));
  const good = c.labels?.good ?? [];
  const dis = c.labels?.distractors ?? [];
  const goodIn = good.filter((k) => poolKeys.has(k));
  const disIn = dis.filter((k) => poolKeys.has(k));
  lines.push("", `## ${c.id}`, "", `${c.description}  `, `Profile: ${c.profile ?? "(none)"}  `, `Articles: ${slugs.length} eligible.`);
  if (c.labels)
    lines.push(
      `  \nExpected-good that are candidates: ${goodIn.join(", ") || "none"}; not candidates: ${good.filter((k) => !poolKeys.has(k)).join(", ") || "none"}.  `,
      `Distractors that are candidates: ${disIn.join(", ") || "none"}; not candidates: ${dis.filter((k) => !poolKeys.has(k)).join(", ") || "none"}.`,
    );
  lines.push("", "| arm | runs | topics | cov@5 | cov@8 | cov@12 | maxJ | maxO | dis | good | $/call | latency s | errors |", "|---|---|---|---|---|---|---|---|---|---|---|---|---|");
  const firsts: string[] = [];
  for (const arm of ARMS) {
    const runs: RunFile[] = [];
    let errors = 0;
    for (const run of RUNS) {
      const file = path.join(RESULTS_DIR, c.id, `${arm}-${run}.json`);
      if (!existsSync(file)) continue;
      const r = JSON.parse(readFileSync(file, "utf8")) as RunFile;
      const s = spend.get(arm) ?? { usd: 0, calls: 0, errors: 0 };
      if (r.call) {
        s.usd += r.call.costUsd || r.call.upstreamCostUsd || 0;
        s.calls += 1;
      }
      if (r.error) {
        errors += 1;
        s.errors += 1;
      }
      spend.set(arm, s);
      if (!r.error) runs.push(r);
    }
    if (!runs.length && !errors) continue;
    const metrics = runs.map((r) => {
      const terms: ShelfTerm[] = r.list.map((t) => ({ key: t.key, label: t.label, articles: t.slugs.map((slug) => ({ slug, count: 1 })) }));
      const h = shelfTermHeadMetrics(terms, slugs);
      const head = new Set(r.list.slice(0, HEAD).map((t) => t.key));
      return {
        h,
        dis: dis.filter((k) => head.has(k)).length,
        good: good.filter((k) => [...head].some((h) => containsPhrase(h, k))).length,
        cost: r.call ? r.call.costUsd || r.call.upstreamCostUsd || 0 : Number.NaN,
        latency: r.call ? r.call.latencyMs / 1000 : Number.NaN,
      };
    });
    const m = (pick: (x: (typeof metrics)[number]) => number) => mean(metrics.map(pick));
    lines.push(
      `| ${armLabel(arm)} | ${runs.length} | ${f1(mean(runs.map((r) => r.list.length)))} | ${f2(m((x) => x.h.coverageAt5))} | ${f2(m((x) => x.h.coverageAt8))} | ${f2(m((x) => x.h.coverageAt12))} | ` +
        `${f2(m((x) => x.h.maxJaccard12))} | ${f2(m((x) => x.h.maxOverlap12))} | ` +
        `${c.labels ? `${f1(m((x) => x.dis))}/${disIn.length}` : "–"} | ${c.labels ? `${f1(m((x) => x.good))}/${goodIn.length}` : "–"} | ` +
        `${Number.isNaN(m((x) => x.cost)) ? "–" : `$${m((x) => x.cost).toFixed(5)}`} | ${f1(m((x) => x.latency))} | ${errors} |`,
    );
    topicCounts.set(`${c.id}|${arm}`, runs.map((r) => r.list.length));
    const first = runs[0];
    if (first)
      firsts.push(`- **${armLabel(arm)}** (run ${first.run}): ${first.list.slice(0, HEAD).map((t) => `${t.label} ${t.count}`).join(", ")}`);
  }
  lines.push("", "First 12, one run of each arm:", "", ...firsts);
}

lines.push("", "## Topics per case, per run (list length)", "", `| case | ${["baseline", "luna-score", ...DERIVED_ARMS].map(armLabel).join(" | ")} |`, "|---|---|---|---|---|");
for (const c of loadCases())
  lines.push(
    `| ${c.id} | ${["baseline", "luna-score", ...DERIVED_ARMS].map((a) => topicCounts.get(`${c.id}|${a}`)?.join("/") ?? "–").join(" | ")} |`,
  );

lines.push(
  "",
  "## Spend by arm (returned usage in the run files, all cases)",
  "",
  "This is a summary of run files with a returned call record, not the spend ledger. A request that failed before returning usage can have spent money and still have no amount here; `npm run cost` is authoritative for recorded attempts.",
  "",
  "| arm | calls | errors | total $ |",
  "|---|---|---|---|",
);
let total = 0;
for (const arm of ARMS) {
  const s = spend.get(arm);
  if (!s || derived.has(arm)) continue;
  total += s.usd;
  lines.push(`| ${arm} | ${s.calls} | ${s.errors} | $${s.usd.toFixed(4)} |`);
}
lines.push(`| **all** | | | **$${total.toFixed(4)}** |`);

writeFileSync(path.join(RESULTS_DIR, "summary.md"), `${lines.join("\n")}\n`);
console.log(`Wrote ${path.join(RESULTS_DIR, "summary.md")} — total recorded spend $${total.toFixed(4)}`);
