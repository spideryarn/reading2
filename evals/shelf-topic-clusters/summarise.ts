/**
 * **The numbers**, free: `npx tsx evals/shelf-topic-clusters/summarise.ts` →
 * `results/summary.md`. Reads this eval's runs and, for comparison, the
 * `baseline` and `luna-score` runs of evals/shelf-topics (today's program list
 * and today's production list) when they are on disk.
 *
 * What each column means is written into the file it generates.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

import { foldKey } from "../../src/shelf-terms/extract.js";
import { EVAL_DIR, loadCases, RESULTS_DIR, type RunFile, type ShelfCase } from "../shelf-topics/case.js";
import { ARMS, OUT_DIR, type RunOut, type Topic } from "./run.js";

interface Row {
  arm: string;
  run: number;
  topics: Topic[];
  usd: number | null;
  secs: number | null;
}

const key = (label: string) =>
  label
    .toLowerCase()
    .split(/[^a-z0-9]+/)
    .filter(Boolean)
    .map((w) => foldKey(w))
    .join(" ");

function load(c: ShelfCase): Row[] {
  const rows: Row[] = [];
  for (const arm of ["baseline", "luna-score"])
    for (const run of [1, 2]) {
      const f = path.join(RESULTS_DIR, c.id, `${arm}-${run}.json`);
      if (!existsSync(f)) continue;
      const r = JSON.parse(readFileSync(f, "utf8")) as RunFile;
      if (r.error) continue;
      rows.push({
        arm: arm === "luna-score" ? "production" : "program-only",
        run,
        topics: r.list.map((t) => ({ label: t.label, slugs: t.slugs })),
        usd: r.call ? r.call.costUsd || r.call.upstreamCostUsd : null,
        secs: r.call ? r.call.latencyMs / 1000 : null,
      });
    }
  for (const arm of ARMS)
    for (const run of [1, 2]) {
      const f = path.join(OUT_DIR, c.id, `${arm}-${run}.json`);
      if (!existsSync(f)) continue;
      const r = JSON.parse(readFileSync(f, "utf8")) as RunOut;
      if (r.error) continue;
      rows.push({
        arm,
        run,
        topics: r.topics,
        usd: r.calls.reduce((s, x) => s + (x.costUsd ?? 0), 0) + (r.embedUsd ?? 0),
        secs: r.calls.reduce((s, x) => s + x.latencyMs, 0) / 1000,
      });
    }
  return rows;
}

const jaccard = (a: Set<string>, b: Set<string>) => {
  let i = 0;
  for (const x of a) if (b.has(x)) i++;
  return i / (a.size + b.size - i || 1);
};

/** Mean, over run 1's topics, of the best member-set Jaccard with any run-2 topic. */
function stability(a: Topic[], b: Topic[]): number {
  if (a.length === 0 || b.length === 0) return 0;
  const bs = b.map((t) => new Set(t.slugs));
  return a.reduce((s, t) => s + Math.max(...bs.map((x) => jaccard(new Set(t.slugs), x))), 0) / a.length;
}

/** For each intended category: the best F1 any topic reaches against its articles. */
function categoryFit(topics: Topic[], intended: Map<string, string[]>): { mean: number; found: number; of: number } {
  const cats = new Map<string, Set<string>>();
  for (const [slug, cs] of intended) for (const c of cs) cats.set(c, (cats.get(c) ?? new Set()).add(slug));
  let sum = 0;
  let found = 0;
  for (const members of cats.values()) {
    let best = 0;
    for (const t of topics) {
      const ts = new Set(t.slugs);
      let hit = 0;
      for (const s of ts) if (members.has(s)) hit++;
      if (hit === 0) continue;
      const p = hit / ts.size;
      const r = hit / members.size;
      best = Math.max(best, (2 * p * r) / (p + r));
    }
    sum += best;
    if (best >= 0.6) found++;
  }
  return { mean: sum / cats.size, found, of: cats.size };
}

const mean = (xs: number[]) => (xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : NaN);
const f2 = (x: number) => (Number.isNaN(x) ? "–" : x.toFixed(2));

const lines: string[] = [
  "# Shelf topics as concepts — the numbers",
  "",
  "Generated by `evals/shelf-topic-clusters/summarise.ts`. Two runs per arm; figures are the mean of the two unless a column says otherwise.",
  "",
  "- **program-only** — today's list with no model (`baseline` in evals/shelf-topics). **production** — today's list: GPT-6 Luna scores the program's phrases (`luna-score`). **induce** and **cluster** — this eval, see `run.ts`.",
  "- **topics** — how many. **first 12** is what the row shows before *All N topics*.",
  "- **cover** — share of the shelf's articles in at least one topic (all topics). **cover@12** — in one of the first 12.",
  "- **multi** — share of articles in two or more topics: what makes choosing a second pill worth it.",
  "- **generic** — labels among the first 12 that are one of the case's planted generic words.",
  "- **same** — run 1 against run 2: for each run-1 topic, the best overlap (Jaccard) of its articles with any run-2 topic, averaged. 1.00 is the same groups twice; it is not a share of identical groups, and two run-1 topics may match one run-2 topic.",
  "- **fit** (greg-wide only, which records the category each article was written for) — for each intended category, the best F1 any topic reaches; then the mean, and how many categories some topic matches at F1 ≥ 0.6.",
  "- **$** — per refresh: every model and embedding call the arm makes. **s** — the model calls only; cluster's two embedding calls are not timed.",
  "",
];

for (const c of loadCases()) {
  const rows = load(c);
  if (rows.length === 0) continue;
  const slugs = c.articles.map((a) => a.slug);
  const distractors = new Set(c.labels?.distractors ?? []);
  const synth = path.join(EVAL_DIR, "synthetic", `${c.id}.json`);
  const intended = new Map<string, string[]>();
  if (existsSync(synth))
    for (const a of (JSON.parse(readFileSync(synth, "utf8")) as { articles: { slug: string; intended?: string[] }[] }).articles)
      if (a.intended) intended.set(a.slug, a.intended);

  lines.push(`## ${c.id}`, "", `${c.articles.length} articles. ${c.description}`, "");
  lines.push(`| arm | topics | cover | cover@12 | multi | generic | same |${intended.size ? " fit | found |" : ""} $ | s |`);
  lines.push(`|---|---|---|---|---|---|---|${intended.size ? "---|---|" : ""}---|---|`);
  const arms = [...new Set(rows.map((r) => r.arm))];
  for (const arm of arms) {
    const rs = rows.filter((r) => r.arm === arm);
    const cover = (ts: Topic[]) => new Set(ts.flatMap((t) => t.slugs)).size / slugs.length;
    const multi = (ts: Topic[]) => slugs.filter((s) => ts.filter((t) => t.slugs.includes(s)).length >= 2).length / slugs.length;
    const generic = (ts: Topic[]) => ts.slice(0, 12).filter((t) => distractors.has(key(t.label))).length;
    const fits = intended.size ? rs.map((r) => categoryFit(r.topics, intended)) : [];
    const usd = rs.map((r) => r.usd).filter((x): x is number => x !== null && x > 0);
    const secs = rs.map((r) => r.secs).filter((x): x is number => x !== null);
    lines.push(
      [
        "",
        arm,
        mean(rs.map((r) => r.topics.length)).toFixed(1),
        f2(mean(rs.map((r) => cover(r.topics)))),
        f2(mean(rs.map((r) => cover(r.topics.slice(0, 12))))),
        f2(mean(rs.map((r) => multi(r.topics)))),
        mean(rs.map((r) => generic(r.topics))).toFixed(1),
        rs.length === 2 ? f2(stability(rs[0]!.topics, rs[1]!.topics)) : "–",
        ...(intended.size ? [f2(mean(fits.map((f) => f.mean))), `${mean(fits.map((f) => f.found)).toFixed(1)} of ${fits[0]?.of}`] : []),
        usd.length ? `$${mean(usd).toFixed(4)}` : "–",
        secs.length ? mean(secs).toFixed(1) : "–",
        "",
      ].join(" | ").trim(),
    );
  }
  lines.push("", "First 12, each run:", "");
  for (const r of rows) lines.push(`- **${r.arm}** (run ${r.run}): ${r.topics.slice(0, 12).map((t) => `${t.label} ${t.slugs.length}`).join(", ")}`);
  lines.push("");
}

writeFileSync(path.join(OUT_DIR, "summary.md"), `${lines.join("\n")}\n`);
console.log(`wrote ${path.join(OUT_DIR, "summary.md")}`);
