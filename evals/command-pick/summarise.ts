/**
 * **Score the saved answers** — free, no model call. Plan 261002c Stage D.
 *
 *     npx tsx evals/command-pick/summarise.ts     # writes results/summary.md and prints it
 *
 * A pick is right when it is in the phrase's `accept` list. A missing or
 * unparseable answer counts as wrong. For Jev, the calibration table asks the
 * question the vision doc does: if we trust Jev only at or above a confidence
 * threshold and send everything else to the chat arm, how often do we fall
 * back, and how often is the final answer right?
 */
import { writeFileSync } from "node:fs";
import path from "node:path";

import { CATALOGUE, NONE } from "./catalogue.js";
import { PHRASES, type Phrase } from "./phrases.js";
import { type Arm, loadRows, RESULTS_DIR, type Row } from "./run.js";

const ARMS: Arm[] = ["jev", "chat"];
const THRESHOLDS = [0.5, 0.6, 0.7, 0.8, 0.9, 0.95];

const byId = new Map(PHRASES.map((p) => [p.id, p]));
const rowsBy: Record<Arm, Map<string, Row>> = {
  jev: new Map(loadRows("jev").map((r) => [r.phrase, r])),
  chat: new Map(loadRows("chat").map((r) => [r.phrase, r])),
};

const right = (p: Phrase, r: Row | undefined): boolean => !!r && r.pick !== null && p.accept.includes(r.pick);
const VALID = new Set([...CATALOGUE.map((c) => c.id), NONE]);
const pct = (n: number, d: number): string => (d ? `${n}/${d} (${Math.round((100 * n) / d)}%)` : "—");
const norm = (s: string): string =>
  s
    .toLowerCase()
    .replace(/["'“”‘’?.!,]/g, "")
    .replace(/\s+/g, " ")
    .trim();

function quantile(xs: number[], q: number): number {
  const s = [...xs].sort((a, b) => a - b);
  return s[Math.min(s.length - 1, Math.floor(q * s.length))] ?? Number.NaN;
}

const out: string[] = [];
out.push("# Command pick — summary", "", `Generated by \`summarise.ts\` from \`jev.json\` and \`chat.json\`. ${PHRASES.length} phrases.`, "");

const sets: [string, (p: Phrase) => boolean][] = [
  ["all", () => true],
  ["round 1 (p01–p46)", (p) => p.style !== "hard"],
  ["round 2, hard (h01–h26)", (p) => p.style === "hard"],
  ["has a right command", (p) => !p.accept.includes(NONE)],
  ["no right command (round 1)", (p) => p.accept.includes(NONE) && p.style !== "hard"],
  ["Greg's examples", (p) => p.style === "greg"],
  ["paraphrase", (p) => p.style === "paraphrase"],
  ["voice-style", (p) => p.style === "voice"],
  ["typo", (p) => p.style === "typo"],
  ["no right command, both rounds", (p) => p.accept.includes(NONE)],
];

out.push("## Accuracy", "", "| set | Jev | chat |", "|---|---|---|");
for (const [name, pred] of sets) {
  const ps = PHRASES.filter(pred);
  const cell = (arm: Arm) => pct(ps.filter((p) => right(p, rowsBy[arm].get(p.id))).length, ps.length);
  out.push(`| ${name} | ${cell("jev")} | ${cell("chat")} |`);
}

out.push("", "## Misses", "", "| phrase | text | accept | Jev | chat |", "|---|---|---|---|---|");
for (const p of PHRASES) {
  const j = rowsBy.jev.get(p.id);
  const c = rowsBy.chat.get(p.id);
  if (right(p, j) && right(p, c)) continue;
  const show = (r: Row | undefined, ok: boolean) =>
    `${ok ? "✓" : "✗"} ${r?.pick ?? r?.error ?? "missing"}${r?.confidence != null ? ` (${r.confidence.toFixed(2)})` : ""}`;
  out.push(`| ${p.id} | ${p.text} | ${p.accept.join(", ")} | ${show(j, right(p, j))} | ${show(c, right(p, c))} |`);
}

for (const arm of ARMS) {
  const bad = [...rowsBy[arm].values()].filter((r) => r.pick !== null && !VALID.has(r.pick));
  if (bad.length) out.push("", `**${arm} answered with ids not in the catalogue:** ${bad.map((r) => `${r.phrase} → \`${r.pick}\``).join(", ")}`);
}

out.push("", "## The argument for find", "", "| phrase | expected | chat's argument | match |", "|---|---|---|---|");
for (const p of PHRASES.filter((x) => x.argument !== undefined)) {
  const got = rowsBy.chat.get(p.id)?.argument ?? null;
  out.push(`| ${p.id} | ${p.argument} | ${got ?? "—"} | ${got !== null && norm(got) === norm(p.argument ?? "") ? "exact" : "no"} |`);
}
out.push("", "Jev returns only a choice among the options, so it has no argument to score.");

out.push("", "## Latency and cost per call", "", "| arm | calls | median ms | p90 ms | max ms | mean $/call | total $ |", "|---|---|---|---|---|---|---|");
let grand = 0;
for (const arm of ARMS) {
  const rows = [...rowsBy[arm].values()];
  const lat = rows.map((r) => r.latencyMs).filter((x): x is number => x !== null);
  const cost = rows.map((r) => r.costUsd ?? 0);
  const total = cost.reduce((a, b) => a + b, 0);
  grand += total;
  out.push(
    `| ${arm} | ${rows.length} | ${quantile(lat, 0.5)} | ${quantile(lat, 0.9)} | ${Math.max(...lat)} | ${(total / rows.length).toFixed(5)} | ${total.toFixed(4)} |`,
  );
}
out.push("", `Total across the saved rows: $${grand.toFixed(4)}. Not counted: the first, truncated attempt at chat p04 (about $0.0096), replaced by its rerun — see the write-up.`);

out.push(
  "",
  "## Jev's confidence as an \"unsure\" signal",
  "",
  "Trust Jev when its `confidence` ≥ t; otherwise fall back to the chat arm's saved answer for the same phrase.",
  "",
  "| phrases | t | Jev trusted | right when trusted | fell back | Jev right on those | combined right |",
  "|---|---|---|---|---|---|---|",
);
for (const [setName, inSet] of [["all", () => true], ["round 2", (p: Phrase) => p.style === "hard"]] as const)
for (const t of THRESHOLDS) {
  const PS = PHRASES.filter(inSet);
  let above = 0;
  let aboveRight = 0;
  let below = 0;
  let belowJevRight = 0;
  let combined = 0;
  for (const p of PS) {
    const j = rowsBy.jev.get(p.id);
    const c = rowsBy.chat.get(p.id);
    if ((j?.confidence ?? 0) >= t) {
      above += 1;
      if (right(p, j)) {
        aboveRight += 1;
        combined += 1;
      }
    } else {
      below += 1;
      if (right(p, j)) belowJevRight += 1;
      if (right(p, c)) combined += 1;
    }
  }
  out.push(
    `| ${setName} | ${t} | ${above} | ${pct(aboveRight, above)} | ${pct(below, PS.length)} | ${pct(belowJevRight, below)} | ${pct(combined, PS.length)} |`,
  );
}

out.push("", "### Jev's confidence, phrase by phrase (lowest first)", "", "| phrase | text | pick | confidence | right |", "|---|---|---|---|---|");
for (const r of [...rowsBy.jev.values()].sort((a, b) => (a.confidence ?? 0) - (b.confidence ?? 0)).slice(0, 20)) {
  const p = byId.get(r.phrase);
  if (!p) continue;
  out.push(`| ${p.id} | ${p.text} | ${r.pick} | ${r.confidence?.toFixed(2)} | ${right(p, r) ? "✓" : "✗"} |`);
}

const text = `${out.join("\n")}\n`;
writeFileSync(path.join(RESULTS_DIR, "summary.md"), text);
console.log(text);
